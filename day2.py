#Numeric Data Types
number=100
percentage=9.4
c=2+3j
print(number,type(number))
print(percentage,type(percentage))
print(c,type(c))

#Sequence Data Types
s='sravanthi'
lst=[10,'sravanthi',9.8]
t=(1,5,8,9,0)
print(s,type(s))
print(lst,type(lst))
print(t,type(t))

#Boolean data types(True/False)
B1=True
B2=False
print(B1,B2,type(B1),type(B2))
print(B1,B2)

#Mapping data types(dictionary) key value pairs
d={'name':'sravanthi',
'age':20,
'percentage':85}
print(d,type(d))

